'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const {browser,tick,cleanup}=require('./ui-helpers.cjs');
const {movieNightsMarkup}=require('../ui/movie-nights');
test.afterEach(cleanup);
const sample={event:{id:'2026-11-21',title:'Movie Night',phase:'voting',startsAt:1795309200000,votingClosesAt:1795308900000,candidates:[{id:10,title:'Test Film',votes:2,year:'2024',runtime:95}],totalVotes:2,viewers:1,messages:[]},viewer:{signedIn:false},upcoming:[],serverTime:1795300000000};
test('premiere presentation preserves the real screening controls and safely escapes data',()=>{
 const html=movieNightsMarkup({snapshot:sample});
 const d=new JSDOM(html).window.document;
 assert(d.querySelector('.nightPremiereBulbs'));
 assert.match(d.querySelector('.nightPremiereTitle').textContent,/lights go down/i);
 assert(d.querySelector('.nightPremierePass'));
 assert(d.querySelector('[data-night-stage]'));
 assert(d.querySelector('[data-night-vote]'));
 assert(d.querySelector('[data-night-chat]'));
 assert(d.querySelector('[data-night-join]'));
 assert(d.querySelector('[data-night-live]'));
 assert(d.querySelector('[data-night-auth-overlay][hidden]'));
 assert(d.querySelector('[data-night-auth-open]'));
 assert(!html.includes('accounts.google.com'));
 const signed=new JSDOM(movieNightsMarkup({snapshot:{...sample,viewer:{signedIn:true,name:'Viewer'}}})).window.document;
 assert.equal(signed.querySelector('[data-night-auth-open]'),null,'signed-in viewers do not get the sign-up banner');
});
test('first-party modal has accessible account modes, password confirmation and no third-party action',()=>{
 const d=new JSDOM(movieNightsMarkup({snapshot:sample})).window.document;
 const dialog=d.querySelector('[data-night-auth-overlay] [role="dialog"]');
 assert.equal(dialog.getAttribute('aria-modal'),'true');
 assert.equal(d.querySelector('[data-night-auth-form]').getAttribute('action'),'/api/connect/auth/signup');
 assert.equal(d.querySelector('[data-night-auth-form]').getAttribute('method'),'post','no password-bearing GET fallback');
 assert.equal(d.querySelector('input[name="password"]').type,'password');
 assert.equal(d.querySelector('input[name="confirmPassword"]').type,'password');
});
test('account setup sends same-origin JSON only after confirmation and can switch to existing login',async()=>{
 const b=browser(movieNightsMarkup({snapshot:sample}),{path:'/movie-nights'}),w=b.window;
 const calls=[];
 w.fetch=async(url,opts={})=>{
  calls.push({url:String(url),opts});
  if(url==='/api/connect/session')return {ok:true,json:async()=>({available:true,user:null})};
  return {ok:false,status:409,json:async()=>({message:'That email or handle already has an account.'})};
 };
 w.boot('community/movie-nights-premiere-auth.js');
 const open=w.document.querySelector('[data-night-auth-open]');
 open.click();await tick();
 const modal=w.document.querySelector('[data-night-auth-overlay]'),form=w.document.querySelector('[data-night-auth-form]');
 assert.equal(modal.hidden,false);
 form.elements.name.value='Test Viewer';
 form.elements.handle.value='testviewer';
 form.elements.email.value='test@example.com';
 form.elements.password.value='a long secret password';
 form.elements.confirmPassword.value='different';
 form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));await tick();
 assert.equal(calls.filter(x=>x.url.endsWith('/auth/signup')).length,0,'mismatched passwords must never be sent');
 assert.match(w.document.querySelector('[data-night-auth-error]').textContent,/do not match/);
 form.elements.confirmPassword.value=form.elements.password.value;
 form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));await tick();
 const signup=calls.find(x=>x.url==='/api/connect/auth/signup');
 assert(signup,'signup must use SwiflyTV account endpoint');
 assert.equal(signup.opts.credentials,'same-origin');
 assert.equal(signup.opts.headers['Content-Type'],'application/json');
 assert.equal(JSON.parse(signup.opts.body).handle,'testviewer');
 assert.match(w.document.querySelector('[data-night-auth-error]').textContent,/already has an account/);
 const loginTab=w.document.querySelector('[data-night-auth-mode="login"]'),authRoot=w.document.querySelector('[data-movie-nights]');
 const tabDiagnostics={insideRoot:authRoot.contains(loginTab),connected:loginTab.isConnected,disabled:loginTab.disabled,tabCount:authRoot.querySelectorAll('[data-night-auth-mode]').length,insideSignin:!!loginTab.closest('[data-night-signin]'),insideOpen:!!loginTab.closest('[data-night-auth-open]'),parentTag:loginTab.parentElement?.tagName};
 let clicked=false;loginTab.addEventListener('click',()=>{clicked=true;});
 loginTab.click();
 assert.equal(clicked,true,'login tab must receive its click event '+JSON.stringify(tabDiagnostics));
 assert.equal(loginTab.getAttribute('aria-selected'),'true','login mode must be selected '+JSON.stringify(tabDiagnostics));
 assert.equal(form.querySelector('input[name="handle"]').disabled,true);
 assert.equal(form.elements.confirmPassword.disabled,true);
 assert.equal(form.elements.password.autocomplete,'current-password');
 assert.equal(w.document.querySelector('[data-night-auth-submit]').textContent,'Sign in to SwiflyTV');
 w.document.querySelector('[data-night-auth-close]').click();
 assert.equal(modal.hidden,true);
 assert.equal(form.elements.password.value,'','password is cleared on close');
});
test('registration clearly fails closed when persistent account storage is unavailable',async()=>{
 const b=browser(movieNightsMarkup({snapshot:sample})),w=b.window;
 w.fetch=async()=>({ok:true,json:async()=>({available:false,user:null})});
 w.boot('community/movie-nights-premiere-auth.js');
 w.document.querySelector('[data-night-auth-open]').click();await tick();
 assert.match(w.document.querySelector('[data-night-auth-error]').textContent,/persistent server storage/);
 assert.equal(w.document.querySelector('[data-night-auth-submit]').disabled,true);
});
